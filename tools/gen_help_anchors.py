#!/usr/bin/env python3
"""Generates C# help-anchor constants from content/help/anchors.yaml (M2.8).

Run directly or via tools/codegen.ps1. Pass --check to verify app/Selah.UI/Services/HelpAnchors.g.cs
matches content/help/anchors.yaml without writing.
"""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
ANCHORS_PATH = ROOT / "content" / "help" / "anchors.yaml"
OUTPUT_PATH = ROOT / "app" / "Selah.UI" / "Services" / "HelpAnchors.g.cs"
ANCHOR_ID = re.compile(r"^[a-z][a-z0-9]*(?:[.-][a-z0-9]+)*$")


def parse_anchors(text: str) -> list[tuple[str, str]]:
    """Extract ordered (id, description) pairs from content/help/anchors.yaml."""
    items: list[tuple[str, str]] = []
    current_id: str | None = None
    current_desc = ""

    def flush():
        nonlocal current_id, current_desc
        if current_id is not None:
            items.append((current_id, current_desc))
            current_id = None
            current_desc = ""

    for number, raw in enumerate(text.splitlines(), 1):
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if stripped == "anchors:":
            continue
        if stripped.startswith("- "):
            rest = stripped[2:].strip()
            if rest.startswith("id:"):
                flush()
                value = rest[3:].strip().strip("\"'")
                if not ANCHOR_ID.match(value):
                    raise ValueError(f"line {number}: invalid anchor id '{value}'")
                current_id = value
                continue
        if stripped.startswith("id:") and current_id is None:
            value = stripped[3:].strip().strip("\"'")
            if not ANCHOR_ID.match(value):
                raise ValueError(f"line {number}: invalid anchor id '{value}'")
            current_id = value
            continue
        if stripped.startswith("description:") and current_id is not None:
            current_desc = stripped[len("description:"):].strip().strip("\"'")
            continue
    flush()
    return items


def to_const_name(anchor_id: str) -> str:
    """Convert `shell.show-test-pattern` to `ShellShowTestPattern`."""
    parts = [p for p in re.split(r"[._-]+", anchor_id) if p]
    return "".join(part[0].upper() + part[1:] for part in parts)


def render_cs(anchors: list[tuple[str, str]]) -> str:
    seen_ids: set[str] = set()
    seen_names: set[str] = set()
    lines = [
        "// <auto-generated>Generated from content/help/anchors.yaml by tools/gen_help_anchors.py. Do not edit.</auto-generated>",
        "namespace Selah.UI.Services;",
        "",
        "/// <summary>Help anchor constants declared in <c>content/help/anchors.yaml</c> (KNOWLEDGE-BASE §5, §7.2).</summary>",
        "public static class HelpAnchors",
        "{",
    ]
    for anchor_id, description in anchors:
        if anchor_id in seen_ids:
            raise ValueError(f"duplicate anchor id '{anchor_id}'")
        seen_ids.add(anchor_id)
        name = to_const_name(anchor_id)
        if name in seen_names:
            raise ValueError(f"duplicate constant name '{name}' for anchor '{anchor_id}'")
        seen_names.add(name)
        safe_desc = description.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        if safe_desc:
            lines.append(f"    /// <summary>{safe_desc}</summary>")
        lines.append(f'    public const string {name} = "{anchor_id}";')
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if the generated file is out of date")
    args = parser.parse_args(argv)

    anchors = parse_anchors(ANCHORS_PATH.read_text(encoding="utf-8"))
    if not anchors:
        print("::error file=content/help/anchors.yaml::no anchors found")
        return 1
    rendered = render_cs(anchors)
    if args.check:
        if not OUTPUT_PATH.exists() or OUTPUT_PATH.read_text(encoding="utf-8") != rendered:
            print(f"::error file={OUTPUT_PATH.relative_to(ROOT).as_posix()}::generated file is out of date; run python tools/gen_help_anchors.py")
            return 1
        print("gen-help-anchors: current")
        return 0
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with OUTPUT_PATH.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(rendered)
    print(f"gen-help-anchors: wrote {len(anchors)} constants -> {OUTPUT_PATH.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
